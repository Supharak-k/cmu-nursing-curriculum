function setLanguage(language) {
  currentLanguage = language;
  page.lang = language;
  document.querySelectorAll(".faculty-logo").forEach(logo => {
    logo.src = `image/web/faculty-logo-${language}.png`;
    logo.alt = language === "th" ? "คณะพยาบาลศาสตร์ มหาวิทยาลัยเชียงใหม่" : "Faculty of Nursing, Chiang Mai University";
  });
  document.querySelectorAll(".brand").forEach(brand => brand.setAttribute("aria-label", language === "th" ? "หน้าแรก คณะพยาบาลศาสตร์ มหาวิทยาลัยเชียงใหม่" : "Faculty of Nursing, Chiang Mai University — home"));
  languageToggle?.classList.toggle("is-en", language === "en");
  languageToggle?.setAttribute("aria-pressed", String(language === "en"));
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[language][key]) element.textContent = translations[language][key].replace(/<br\s*\/?\s*>/gi, " ");
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const key = element.dataset.i18nHtml;
    if (translations[language][key]) element.innerHTML = translations[language][key];
  });
  document.querySelectorAll("[data-th][data-en]").forEach((element) => {
    const value = language === "th" ? element.dataset.th : element.dataset.en;
    if (element.hasAttribute("data-lang-html")) element.innerHTML = value;
    else element.textContent = value;
  });
  const pageTitle = document.body.dataset[language === "th" ? "titleTh" : "titleEn"];
  if (pageTitle) document.title = pageTitle;
  const pageDesc = document.body.dataset[language === "th" ? "descTh" : "descEn"];
  const descMeta = document.querySelector('meta[name="description"]');
  if (pageDesc && descMeta) descMeta.content = pageDesc;
  renderHeroSlide(activeHeroSlide);
  updateMotionLabel();
}

