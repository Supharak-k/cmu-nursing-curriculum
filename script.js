// Motion responds to input; no continuous JavaScript render loop is needed.
const reducedMotion = matchMedia("(prefers-reduced-motion: reduce)");
const finePointer = matchMedia("(hover: hover) and (pointer: fine)");
const motionToggle = document.querySelector(".footer-motion-toggle") || document.querySelector(".motion-toggle");
let motionPaused = reducedMotion.matches;
function motionEnabled() { return !motionPaused && !reducedMotion.matches; }
function updateMotionLabel() {
  if (!motionToggle) return;
  motionToggle.textContent = currentLanguage === "th"
    ? (motionPaused ? "เปิดการเคลื่อนไหว" : "หยุดการเคลื่อนไหว")
    : (motionPaused ? "Enable motion" : "Pause motion");
  motionToggle.setAttribute("aria-pressed", String(motionPaused));
}
function applyMotionPreference() {
  page.classList.toggle("motion-paused", motionPaused);
  page.classList.toggle("motion-ready", motionEnabled());
  updateMotionLabel();
  document.querySelectorAll(".program-card, .hero-visual").forEach(el => {
    ["--tilt-x", "--tilt-y", "--hero-x", "--hero-shift"].forEach(name => el.style.removeProperty(name));
  });
}
motionToggle?.addEventListener("click", () => {
  motionPaused = !motionPaused;
  applyMotionPreference();
});
reducedMotion.addEventListener("change", () => {
  motionPaused = reducedMotion.matches;
  applyMotionPreference();
});
applyMotionPreference();

document.querySelectorAll(".program-card, .hero-visual").forEach(el => {
  el.addEventListener("pointermove", event => {
    if (!motionEnabled() || !finePointer.matches) return;
    const bounds = el.getBoundingClientRect();
    const x = (event.clientX - bounds.left) / bounds.width - .5;
    const y = (event.clientY - bounds.top) / bounds.height - .5;
    el.style.setProperty("--tilt-x", `${-y * 8}deg`);
    el.style.setProperty("--tilt-y", `${x * 8}deg`);
    el.style.setProperty("--hero-x", `${x * 12}deg`);
    el.style.setProperty("--hero-shift", `${x * 18}px`);
  });
  el.addEventListener("pointerleave", () => {
    ["--tilt-x", "--tilt-y", "--hero-x", "--hero-shift"].forEach(name => el.style.removeProperty(name));
  });
});

const journeySection = document.querySelector(".journey");
const journeySteps = [...document.querySelectorAll(".journey-step")];
let scrollFrame = 0;
function updateScrollScene() {
  scrollFrame = 0;
  const total = document.documentElement.scrollHeight - innerHeight;
  page.style.setProperty("--read", total > 0 ? scrollY / total : 0);
  if (journeySection) {
    const bounds = journeySection.getBoundingClientRect();
    const progress = Math.max(0, Math.min(1, (innerHeight * .7 - bounds.top) / bounds.height));
    page.style.setProperty("--journey", progress);
    let nearest = null;
    let distance = Infinity;
    journeySteps.forEach(step => {
      const delta = Math.abs(step.getBoundingClientRect().top - innerHeight * .45);
      if (delta < distance) { distance = delta; nearest = step; }
    });
    journeySteps.forEach(step => step.classList.toggle("is-current", step === nearest));
  }
}
function queueScrollScene() {
  if (!scrollFrame) scrollFrame = requestAnimationFrame(updateScrollScene);
}
