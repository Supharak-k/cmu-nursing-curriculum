let activeHeroSlide = 0;

function animateHeroWords(element, text) {
  let wordIndex = 0;
  element.innerHTML = text.split("\n").map(line => `<span class="hero-line">${line.split(/\s+/).map(word =>
    `<span class="hero-word" style="--word-index:${wordIndex++}">${word}</span>`
  ).join(" ")}</span>`).join("");
}

function renderHeroSlide(index = activeHeroSlide) {
  const title = document.querySelector(".hero h1");
  const lede = document.querySelector(".hero .hero-lede");
  const slide = competencySlides[currentLanguage]?.[index];
  if (!title || !lede || !slide) return;
  activeHeroSlide = index;
  animateHeroWords(title, slide.title);
  animateHeroWords(lede, slide.lede);
}

function startHeroSlideRotation() {
  if (!document.querySelector(".hero h1")) return;
  renderHeroSlide(0);
  window.setInterval(() => {
    activeHeroSlide = (activeHeroSlide + 1) % competencySlides[currentLanguage].length;
    renderHeroSlide(activeHeroSlide);
  }, 15000);
}

